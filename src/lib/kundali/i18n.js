const DICTS = { en, hi };

/** Dictionary of a language (falls back to English). */
export const dict = (lang) => DICTS[lang] || en;
export const isLang = (lang) => Boolean(DICTS[lang]);

/** Formats an instant as a date in the birth place's zone, in the chosen language. */
export function fmtDate(ms, lang, timeZone = "Asia/Kolkata") {
  if (ms == null) return "-";
  return new Intl.DateTimeFormat(lang === "hi" ? "hi-IN" : "en-IN", { day: "numeric", month: "short", year: "numeric", timeZone }).format(new Date(ms));
}
/** HH:MM:SS (24 h) of an instant in a zone. */
export function fmtTime(ms, timeZone = "Asia/Kolkata", seconds = true) {
  if (ms == null) return "-";
  return new Intl.DateTimeFormat("en-GB", { hour: "2-digit", minute: "2-digit", second: seconds ? "2-digit" : undefined, hourCycle: "h23", timeZone }).format(new Date(ms));
}
/** "YYYY-MM-DD" input date shown in the chosen language. */
export const fmtInputDate = (date, lang) => fmtDate(Date.parse(`${date}T12:00:00Z`), lang, "UTC");
